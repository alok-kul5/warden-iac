"""Compare warden with checkov on the labelled example stacks.

    pip install checkov
    python bench/compare.py            # writes bench/RESULTS.md

Each example marks the resources that should be flagged with `# expect: RULE`.
For warden a label counts as caught only when the same rule fires on the same
resource. For checkov we are generous: a label counts as caught when checkov
fails *any* check on that resource or, for IAM labels, on a policy resource with
the same name (the fixtures name a user's policy after the user).
"""

from __future__ import annotations

import json
import shutil
import subprocess
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "tests"))

from test_examples import labels  # noqa: E402

from warden.scanner import scan  # noqa: E402

STACKS = ["startup-stack", "iam-escalation", "hardened"]
IAM_TYPES = ("aws_iam_user_policy", "aws_iam_role_policy", "aws_iam_group_policy", "aws_iam_policy",
             "aws_iam_user_policy_attachment", "aws_iam_role_policy_attachment", "aws_iam_user", "aws_iam_role")


def checkov(stack: Path) -> tuple[list[dict], float, str]:
    exe = shutil.which("checkov")
    if not exe:
        sys.exit("checkov is not on PATH: pip install checkov")
    t = time.perf_counter()
    out = subprocess.run([exe, "-d", str(stack), "--framework", "terraform", "-o", "json", "--quiet", "--compact",
                          "--skip-download"], capture_output=True, text=True, encoding="utf-8")
    took = time.perf_counter() - t
    doc = json.loads(out.stdout or "{}")
    docs = doc if isinstance(doc, list) else [doc]
    failed = [c for d in docs for c in d.get("results", {}).get("failed_checks", [])]
    version = subprocess.run([exe, "--version"], capture_output=True, text=True).stdout.strip()
    return failed, took, version


def related(label_resource: str, failed_resource: str) -> bool:
    if failed_resource == label_resource:
        return True
    ltype, _, lname = label_resource.partition(".")
    ftype, _, fname = failed_resource.partition(".")
    return ltype.startswith("aws_iam_") and ftype in IAM_TYPES and fname == lname


def main() -> int:
    rows, privesc, version = [], [], ""
    for name in STACKS:
        stack = ROOT / "examples" / name
        want = labels(stack)
        t = time.perf_counter()
        res = scan(stack)
        w_time = time.perf_counter() - t
        got = {(f.rule.id, f.resource) for f in res.findings}
        failed, c_time, version = checkov(stack)
        c_res = {c["resource"] for c in failed}
        w_hit = len(want & got)
        c_hit = sum(1 for _, r in want if any(related(r, x) for x in c_res))
        rows.append((name, len(want), w_hit, len(got - want), c_hit, len(failed), len(c_res), w_time, c_time))
        for rule, r in sorted(want):
            if rule == "WDN-IAM-001":
                ids = sorted({c["check_id"] for c in failed if related(r, c["resource"])})
                privesc.append((r, ids))

    md = [f"# warden vs checkov on the example stacks", "",
          f"Generated by `python bench/compare.py` with {version.splitlines()[0] if version else 'checkov'}.", "",
          "| Stack | Labelled issues | warden caught | warden extra | checkov caught (any check on the resource) | checkov failed checks | checkov resources flagged | warden time | checkov time |",
          "|---|---:|---:|---:|---:|---:|---:|---:|---:|"]
    for n, lab, wh, wx, ch, cf, cr, wt, ct in rows:
        md.append(f"| {n} | {lab} | {wh}/{lab} | {wx} | {ch}/{lab} | {cf} | {cr} | {wt:.2f}s | {ct:.1f}s |")
    md += ["", "## Escalation paths", "",
           "Each row is a principal that warden shows can reach admin. The checkov column lists the checks that",
           "failed on that principal or its same-named policy.", "",
           "| Principal | checkov checks on it |", "|---|---|"]
    md += [f"| `{r}` | {', '.join(ids) if ids else 'none'} |" for r, ids in privesc]
    (ROOT / "bench" / "RESULTS.md").write_text("\n".join(md) + "\n", encoding="utf-8")
    print("\n".join(md))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
